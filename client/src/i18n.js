export const dictionaries = { fr, en };

export const LanguageContext = createContext({
  lang: 'fr',
  setLang: () => {},
  t: (key, params = {}) => key,
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('bo_lang') || 'fr');
  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem('bo_lang', l);
  };
  const t = (key, params = {}) => {
    const dict = dictionaries[lang] || dictionaries.fr;
    let str = dict[key] ?? dictionaries.fr[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) str = str.replaceAll(`{${k}}`, String(v));
    }
    return str;
  };
  return createElement(LanguageContext.Provider, { value: { lang, setLang, t } }, children);
}

export const useLanguage = () => useContext(LanguageContext);
